// Fabricated; each contains FAKEsecret, so one search finds any leak.
const SK = 'sk-FAKEsecret0123456789abcdef';
const GRAPH = `<!-- creole graph v2 · pass 1 · 2026-10-19T10:00:00Z · 125000 tokens -->
T: Port the CLI to Rust
C1: "no async runtime"
B1: \`src/args.rs\`: clap parser
D1: \`src/args.rs\`: derive API over the builder
S1: config loading | in progress | remaining: env overrides
L: Argument parser done`;
const USERS = ['Port the CLI to Rust; "no async runtime", please.'];
const count = (text, mark) => String(text).split(mark).length - 1;
const hasGit = spawnSync('git', ['--version']).status === 0;

const temp = (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'creole-project-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return realpathSync(dir);
};
const write = (root, path, text) => {
  mkdirSync(dirname(join(root, path)), { recursive: true });
  writeFileSync(join(root, path), text);
};

